"""Blender-independent mask configuration models."""

from dataclasses import dataclass
from typing import Annotated, Literal, Union

from pydantic import Field

from terrain_layers.paths.path_types import DeformationSettings


@dataclass(frozen=True, slots=True)
class HeightMask:
    type: Literal["height"] = Field(default="height", description="Mask variant identifier.")
    min_height: float = Field(default=0.0, description="World-space height where the mask starts to become active.")
    max_height: float = Field(default=10.0, description="World-space height where the mask becomes fully active.")
    ramp_low: float = Field(default=0.4, description="Normalized position of the lower smoothing ramp between the height limits.")
    ramp_high: float = Field(default=0.6, description="Normalized position of the upper smoothing ramp between the height limits.")


@dataclass(frozen=True, slots=True)
class SlopeMask:
    type: Literal["slope"] = Field(default="slope", description="Mask variant identifier.")
    min_angle: float = Field(default=25.0, description="Surface slope angle in degrees where the mask starts to become active.")
    max_angle: float = Field(default=60.0, description="Surface slope angle in degrees where the mask becomes fully active.")
    ramp_low: float = Field(default=0.4, description="Normalized position of the lower smoothing ramp between the slope limits.")
    ramp_high: float = Field(default=0.6, description="Normalized position of the upper smoothing ramp between the slope limits.")


@dataclass(frozen=True, slots=True)
class PaintMask:
    type: Literal["paint"] = Field(default="paint", description="Mask variant identifier.")
    image_name: str = Field(default="IMG_TerrainPaintMask", description="Name of the Blender image that stores the painted mask.")
    uv_map_name: str = Field(default="UV_TerrainPaintMask", description="Name of the UV map used to read and paint the mask image.")
    width: int = Field(default=1024, description="Width, in pixels, of a newly created paint-mask image.")
    height: int = Field(default=1024, description="Height, in pixels, of a newly created paint-mask image.")
    alpha: bool = Field(default=True, description="Create the paint-mask image with an alpha channel.")
    ramp_low: float = Field(default=0.0, description="Input mask value at the low end of the paint-mask remapping ramp.")
    ramp_high: float = Field(default=1.0, description="Input mask value at the high end of the paint-mask remapping ramp.")
    interpolation: Literal["Linear", "Closest", "Cubic", "Smart"] = Field(default="Linear", description="Interpolation mode used when sampling the paint-mask image.")
    extension: Literal["REPEAT", "EXTEND", "CLIP", "MIRROR"] = Field(default="CLIP", description="How image coordinates outside the UV range are handled.")


@dataclass(frozen=True, slots=True)
class ScatterFootprintMask:
    """A soft terrain mask around points generated by a scatter biome."""

    type: Literal["scatter_footprint"] = Field(
        default="scatter_footprint", description="Mask variant identifier."
    )
    scatter_biome_id: str = Field(default="", description="Identifier of the scatter biome whose instances create this footprint.")
    inner_radius: float = Field(default=0.75, description="Radius around each instance that is fully masked.")
    outer_radius: float = Field(default=1.5, description="Radius around each instance where the mask fades to zero.")


@dataclass(frozen=True, slots=True)
class RoadPathSettings:
    width: float = Field(default=2.5, description="Full width of the road mask around each projected path.")
    falloff: float = Field(default=1.0, description="Distance outside the road width over which the mask fades out.")
    sample_count: int = Field(default=32, description="Number of samples used to approximate each curve segment.")
    ray_length: float = Field(default=10000.0, description="Maximum distance used to find the terrain surface below each path point.")
    ramp_low: float = Field(default=0.0, description="Input mask value at the low end of the road-mask remapping ramp.")
    ramp_high: float = Field(default=1.0, description="Input mask value at the high end of the road-mask remapping ramp.")
    deformation_settings: DeformationSettings = Field(default_factory=DeformationSettings, description="Optional terrain-deformation settings shared by paths using these defaults.")


@dataclass(frozen=True, slots=True)
class RoadPathSettingsOverride:
    width: float | None = Field(default=None, description="Per-path replacement for the shared road-mask width.")
    falloff: float | None = Field(default=None, description="Per-path replacement for the shared road-mask falloff.")
    sample_count: int | None = Field(default=None, description="Per-path replacement for the shared curve sampling count.")
    ray_length: float | None = Field(default=None, description="Per-path replacement for the distance used to find the terrain surface.")
    ramp_low: float | None = Field(default=None, description="Per-path replacement for the shared lower mask-remapping ramp value.")
    ramp_high: float | None = Field(default=None, description="Per-path replacement for the shared upper mask-remapping ramp value.")
    deformation_settings: DeformationSettings | None = Field(default=None, description="Per-path replacement for the shared terrain-deformation settings.")


@dataclass(frozen=True, slots=True)
class RoadNetworkPath:
    """One object or collection used as a source in a road network."""

    path_object_name: str | None = Field(default=None, description="Name of one Blender curve object to include in the road network.")
    path_collection_name: str | None = Field(default=None, description="Name of a Blender collection whose curve objects are included in the road network.")
    path_settings: RoadPathSettingsOverride | None = Field(default=None, description="Settings that override the network defaults for this object or collection.")


@dataclass(frozen=True, slots=True)
class RoadNetworkMask:
    """A combined mask from multiple terrain-projected curve paths."""

    type: Literal["road_network"] = Field(
        default="road_network", description="Mask variant identifier."
    )
    paths: list[RoadNetworkPath] = Field(default_factory=list, description="Curve-object and collection sources that form the combined road mask.")
    path_settings: RoadPathSettings = Field(default_factory=RoadPathSettings, description="Default settings used by every road path unless it supplies an override.")
    path_inactive_areas_collection: str | None = Field(default=None, description="Optional collection whose geometry marks areas where roads should have no effect.")


Mask = Annotated[
    Union[HeightMask, SlopeMask, PaintMask, RoadNetworkMask, ScatterFootprintMask],
    Field(discriminator="type"),
]
