"""Blender-independent mask configuration models."""

from dataclasses import dataclass, field
from typing import Annotated, Literal, Union

from pydantic import Field

from terrain_layers.paths.path_types import DeformationSettings


@dataclass(frozen=True, slots=True)
class HeightMask:
    type: Literal["height"] = "height"
    min_height: float = 0.0
    max_height: float = 10.0
    ramp_low: float = 0.4
    ramp_high: float = 0.6


@dataclass(frozen=True, slots=True)
class SlopeMask:
    type: Literal["slope"] = "slope"
    min_angle: float = 25.0
    max_angle: float = 60.0
    ramp_low: float = 0.4
    ramp_high: float = 0.6


@dataclass(frozen=True, slots=True)
class PaintMask:
    type: Literal["paint"] = "paint"
    image_name: str = "IMG_TerrainPaintMask"
    uv_map_name: str = "UV_TerrainPaintMask"
    width: int = 1024
    height: int = 1024
    alpha: bool = True
    ramp_low: float = 0.0
    ramp_high: float = 1.0
    interpolation: Literal["Linear", "Closest", "Cubic", "Smart"] = "Linear"
    extension: Literal["REPEAT", "EXTEND", "CLIP", "MIRROR"] = "CLIP"


@dataclass(frozen=True, slots=True)
class ScatterFootprintMask:
    """A soft terrain mask around points generated by a scatter biome."""

    type: Literal["scatter_footprint"] = "scatter_footprint"
    scatter_biome_id: str = ""
    inner_radius: float = 0.75
    outer_radius: float = 1.5


@dataclass(frozen=True, slots=True)
class RoadPathSettings:
    width: float = 2.5
    falloff: float = 1.0
    sample_count: int = 32
    ray_length: float = 10000.0
    ramp_low: float = 0.0
    ramp_high: float = 1.0
    deformation_settings: DeformationSettings = field(
        default_factory=DeformationSettings
    )


@dataclass(frozen=True, slots=True)
class RoadPathSettingsOverride:
    width: float | None = None
    falloff: float | None = None
    sample_count: int | None = None
    ray_length: float | None = None
    ramp_low: float | None = None
    ramp_high: float | None = None
    deformation_settings: DeformationSettings | None = None


@dataclass(frozen=True, slots=True)
class RoadNetworkPath:
    """One object or collection used as a source in a road network."""

    path_object_name: str | None = None
    path_collection_name: str | None = None
    path_settings: RoadPathSettingsOverride | None = None


@dataclass(frozen=True, slots=True)
class RoadNetworkMask:
    """A combined mask from multiple terrain-projected curve paths."""

    type: Literal["road_network"] = "road_network"
    paths: list[RoadNetworkPath] = field(default_factory=list)
    path_settings: RoadPathSettings = field(default_factory=RoadPathSettings)
    path_inactive_areas_collection: str | None = None


Mask = Annotated[
    Union[HeightMask, SlopeMask, PaintMask, RoadNetworkMask, ScatterFootprintMask],
    Field(discriminator="type"),
]
